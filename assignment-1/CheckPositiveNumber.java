/**
 * Program to check whether a number is positive.
 * LB Assignment-1: Question 1
 */
public class CheckPositiveNumber {
    public static void main(String[] args) {
        int num = 5; // Predefined number

        if (num > 0) {
            System.out.println(num + " is a Positive Number");
        } else {
            System.out.println(num + " is Not a Positive Number");
        }
    }
}
